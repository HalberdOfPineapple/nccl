def card(experiment):
    rows = ''.join(f'<tr><th scope="row">{html.escape(key)}</th><td>{html.escape(value)}</td></tr>' for key, value in experiment['runs'])
    diagrams = ''
    for arm in experiment['arms']:
        heading = f'<h4>{html.escape(arm["arm"])}</h4>' if 'arm' in arm else ''
        diagrams += f'\n  {heading}<div class="frame">\n  {diagram(arm)}\n  </div>'
    return (f'<article class="expcard" id="{experiment["id"]}">\n  <h3>{html.escape(experiment["title"])}</h3>\n'
            f'  <p class="question">{html.escape(experiment["question"])}</p>\n'
            f'  <div class="tablewrap"><table class="runs"><tbody>{rows}</tbody></table></div>{diagrams}\n</article>')


def section():
    cards = '\n'.join(card(experiment) for experiment in EXPERIMENTS)
    index = ' '.join(f'<a href="#{experiment["id"]}">{html.escape(experiment["title"].split(" · ")[0])}</a>' for experiment in EXPERIMENTS)
    return f'''{START}
<section id="path">
  <span class="eyebrow">1 · Data paths, one per experiment</span>
  <h2>What each experiment runs, and where its bytes go</h2>
  <p>Every diagram has the same layout: SMs at the top, HBM at the bottom, source GPU on the left, destination on the right. Only the roles that run in that experiment are drawn in color; other SMs hold idle CTAs. A red dashed outline marks a part that both flows pass through in that experiment.</p>
  <div class="pathlegend"><span><i class="lg copy"></i>Copy bytes</span><span><i class="lg co"></i>Co-runner writes</span><span><i class="lg coread"></i>Co-runner reads</span><span><i class="lg shared"></i>Part both flows use</span><span><i class="lg idle"></i>Idle CTAs</span></div>
  <nav class="expindex" aria-label="Experiments">{index}</nav>
  {MARKERS}
{cards}
</section>
{END}'''


