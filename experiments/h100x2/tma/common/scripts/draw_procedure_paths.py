def rect(box, css, radius=4):
    return f'<rect class="{css}" x="{box["x"]}" y="{box["y"]}" width="{box["w"]}" height="{box["h"]}" rx="{radius}"/>'


def text(x, y, content, css=''):
    attribute = f' class="{css}"' if css else ''
    return f'<text{attribute} x="{x}" y="{y}">{html.escape(content)}</text>'


def arrow(points, css, marker):
    path = 'M' + ' L'.join(f'{x},{y}' for x, y in points)
    return f'<path class="{css}" d="{path}" marker-end="url(#{marker})"/>'


def shared_outline(box, label):
    """Red dashed outline around a part both flows use (hover shows the label)."""
    # The page legend names the red outline; a label inside the box collided with arrows.
    return f'<rect class="sharedmark" x="{box["x"] - 3}" y="{box["y"] - 3}" width="{box["w"] + 6}" height="{box["h"] + 6}" rx="6"><title>{html.escape(label)}</title></rect>'


