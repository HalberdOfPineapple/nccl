def result_line(experiment):
    css = {'hit': 'hittext', 'ok': 'oktext', 'none': 'title'}[experiment['result_kind']]
    return [text(24, 398, experiment['result'], css), text(24, 414, experiment.get('result_note', ''), 'small')]


def diagram(experiment):
    parts = skeleton(experiment)
    if experiment['copy']:
        parts += copy_flow()
    flow = experiment.get('flow')
    if flow == 'other_write':
        parts += other_sm_write_flow()
    elif flow == 'other_read':
        parts += other_sm_read_flow()
    elif flow == 'same_tma':
        parts += same_sm_writer('tma')
    elif flow == 'same_thread':
        parts += same_sm_writer('thread')
    elif flow == 'destination':
        parts += destination_write_flow()
    for box, label in experiment.get('shared', []):
        parts.append(shared_outline(box, label))
    parts += result_line(experiment)
    body = '\n    '.join(parts)
    return (f'<svg viewBox="0 0 1000 424" role="img" aria-label="{html.escape(experiment["aria"])}">\n    {body}\n  </svg>')


